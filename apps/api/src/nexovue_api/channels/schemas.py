"""Notification channel shapes (F21, FR1, FR23). No response carries a secret (BR6)."""

from __future__ import annotations

import uuid
from datetime import datetime
from typing import Annotated, Any, Literal

from pydantic import AwareDatetime, BaseModel, Field

ChannelName = Annotated[str, Field(min_length=1, max_length=120)]
# The kinds a person creates. `owners` exists once per organization, from signup.
CreatableKind = Literal["email", "slack", "teams", "discord", "pagerduty", "webhook"]


class RuleUsingChannel(BaseModel):
    id: uuid.UUID
    name: str
    project_id: uuid.UUID


class ChannelSummary(BaseModel):
    id: uuid.UUID
    kind: str
    name: str
    # What may be shown: addresses, a webhook URL, PagerDuty's region.
    config: dict[str, Any]
    # Where it delivers, as a host — never a path, which is a credential for Slack
    # and Discord.
    destination: str | None
    secret_set: bool
    health: Literal["healthy", "failing"]
    failing_since: datetime | None
    last_delivered_at: datetime | None
    muted_until: datetime | None
    muted_by: uuid.UUID | None
    # When warnings wait (FR15): timezone, days (Monday is 0), start and end.
    quiet_hours: dict[str, Any] | None
    created_at: datetime
    # Which rules send here — what deleting it would silence (FR25).
    rules: list[RuleUsingChannel]


class CreatedChannel(ChannelSummary):
    # A generic webhook's signing secret, generated by nexovue and shown this once
    # (FR1). Absent for every other kind.
    signing_secret: str | None = None


class ChannelListResponse(BaseModel):
    channels: list[ChannelSummary]


class CreateChannelRequest(BaseModel):
    kind: CreatableKind
    name: ChannelName
    config: dict[str, Any] = {}
    # Slack, Teams and Discord: the webhook URL. PagerDuty: the routing key.
    secret: str | None = None


class UpdateChannelRequest(BaseModel):
    """A partial edit. A secret is replaced, never read back (FR23)."""

    name: ChannelName | None = None
    config: dict[str, Any] | None = None
    secret: str | None = None


class QuietHoursRequest(BaseModel):
    """Set, or cleared when absent (FR15). Only for channels people read."""

    quiet_hours: dict[str, Any] | None = None


class MuteChannelRequest(BaseModel):
    """Muted until then, or unmuted when absent (FR14)."""

    until: AwareDatetime | None = None


class SigningSecret(BaseModel):
    signing_secret: str


class SendTestAccepted(BaseModel):
    request_id: str


class SendTestResult(BaseModel):
    # False while the worker has not answered yet: `pending` says which.
    pending: bool
    delivered: bool = False
    http_status: int | None = None
    reason: str | None = None


class DeliveryAttempt(BaseModel):
    id: uuid.UUID
    attempted_at: datetime
    # delivered, retrying or failed — the column's CHECK constraint.
    outcome: str
    http_status: int | None
    reason: str | None
    # What the attempt was about: incident subjects and what happened to them.
    notifications: list[str]


class DeliveryLogResponse(BaseModel):
    attempts: list[DeliveryAttempt]
