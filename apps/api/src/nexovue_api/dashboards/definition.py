"""What a dashboard may hold, and the only way a definition enters (F20, design section 3).

Two shapes. A **definition** holds the panels and how they are laid out, and no title or
description, which are columns. A **dashboard document** wraps it with a title and a
description, and is what a save, a draft and a file carry.

**Writing is strict, reading is forgiving.** `parse_document` refuses a whole document
for any unknown field, unknown kind, setting outside the spec's allowed-values table,
or a cap exceeded (FR7), so nothing resembling a query can be stored (BR2). A stored
definition is read panel by panel by `parse_stored`: a panel the code no longer knows
reads `unknown_kind`, and the rest of the page still draws (FR8).

**Free text.** Titles, link labels and panel titles refuse control and invisible
characters, so `checkout` and `checkout` with a zero-width space cannot both pass the
unique index or deceive a reader (FR61, BR10). Descriptions and notes may hold any text,
which the console only ever shows as text with such characters made visible; only NUL
is refused there, because Postgres cannot store it.

Step 2 knew three kinds; Step 4 adds `top_services_trend` and `node_trend` (plan, T4.1,
T4.2). Every value marked as a cap is the spec's *guess* until plan T5.7 measures it.
"""

from __future__ import annotations

import json
import unicodedata
from typing import Annotated, Any, Final, Literal
from urllib.parse import parse_qsl, urlsplit

from pydantic import (
    AfterValidator,
    BaseModel,
    ConfigDict,
    Field,
    StringConstraints,
    TypeAdapter,
    ValidationError,
    model_validator,
)

from nexovue_api.dashboards.ranges import RangeId
from nexovue_api.data.postgres.models import (
    DASHBOARD_DESCRIPTION_MAX_LENGTH,
    DASHBOARD_TITLE_MAX_LENGTH,
)
from nexovue_api.errors.exceptions import InvalidRequestError
from nexovue_api.infrastructure.conventions import INFRASTRUCTURE_METRIC_NAMES

SCHEMA_VERSION: Final = 1

MAX_PANELS: Final = 30
MAX_DOCUMENT_BYTES: Final = 64 * 1024
MAX_LINKS: Final = 5
NOTE_MAX_LENGTH: Final = 2_000
# A service name, as long as the metrics route's bound on a name it binds.
NAME_MAX_LENGTH: Final = 255
# A panel title and a link label are short labels, held to a dashboard title's length.
LABEL_MAX_LENGTH: Final = DASHBOARD_TITLE_MAX_LENGTH
# An address a browser and a wiki both accept without complaint.
LINK_MAX_LENGTH: Final = 2_048
# Generated by the console, unique within a definition, and safe in an address.
PANEL_ID_PATTERN: Final = r"^[A-Za-z0-9_-]{1,32}$"

# Unicode categories shown to nobody: controls, format characters (zero-width, bidi
# overrides, tags), line and paragraph separators, surrogates and private use.
_INVISIBLE_CATEGORIES: Final = frozenset({"Cc", "Cf", "Zl", "Zp", "Cs", "Co"})
NUL: Final = "\x00"

# The masking rule's credential markers (`apps/workers/internal/pipeline/mask/rules.go`),
# which `test_dashboard_definition.py` holds equal. A link whose query names one is
# refused, as masking would have blanked it in telemetry (FR56).
CREDENTIAL_KEY_MARKERS: Final = ("password", "secret", "api_key", "apikey", "api-key")
# Matched alone, except right before a trailing "s": a count of tokens is not a credential.
TOKEN_MARKER: Final = "token"
HTTPS: Final = "https"

UNKNOWN_KIND: Final = "unknown_kind"


def _refuse_invisible(value: str) -> str:
    for character in value:
        if unicodedata.category(character) in _INVISIBLE_CATEGORIES:
            raise ValueError(
                f"holds an invisible or control character, U+{ord(character):04X}; "
                "type the name without it"
            )
    return value


def _refuse_nul(value: str) -> str:
    if NUL in value:
        raise ValueError("holds a NUL character, which cannot be stored")
    return value


def _names_a_credential(key: str) -> bool:
    lowered = key.lower()
    if any(marker in lowered for marker in CREDENTIAL_KEY_MARKERS):
        return True
    start = lowered.find(TOKEN_MARKER)
    while start != -1:
        after = start + len(TOKEN_MARKER)
        if lowered[after : after + 1] != "s":
            return True
        start = lowered.find(TOKEN_MARKER, after)
    return False


def _plain_https(value: str) -> str:
    """An `https` address naming a host, with no person in it and no credential in its
    query: `javascript:` and `https://wiki.example@evil.test/` both fail here (FR56)."""
    _refuse_invisible(value)
    parts = urlsplit(value)
    if parts.scheme.lower() != HTTPS:
        raise ValueError("must be an https address")
    if "@" in parts.netloc or parts.username is not None or parts.password is not None:
        raise ValueError("must not hold a user name or password")
    if not parts.hostname:
        raise ValueError("must name a host")
    for key, _ in parse_qsl(parts.query, keep_blank_values=True):
        if _names_a_credential(key):
            raise ValueError(f"must not carry a credential in its query ({key!r})")
    return value


Label = Annotated[
    str,
    StringConstraints(min_length=1, max_length=LABEL_MAX_LENGTH),
    AfterValidator(_refuse_invisible),
]
Title = Annotated[
    str,
    StringConstraints(min_length=1, max_length=DASHBOARD_TITLE_MAX_LENGTH),
    AfterValidator(_refuse_invisible),
]
Description = Annotated[
    str,
    StringConstraints(max_length=DASHBOARD_DESCRIPTION_MAX_LENGTH),
    AfterValidator(_refuse_nul),
]
NoteText = Annotated[
    str, StringConstraints(max_length=NOTE_MAX_LENGTH), AfterValidator(_refuse_nul)
]
# Bound in SQL as a parameter, never spliced, so any text a service sends is a name.
ServiceName = Annotated[
    str, StringConstraints(min_length=1, max_length=NAME_MAX_LENGTH), AfterValidator(_refuse_nul)
]
PanelId = Annotated[str, StringConstraints(pattern=PANEL_ID_PATTERN)]
LinkAddress = Annotated[
    str, StringConstraints(min_length=1, max_length=LINK_MAX_LENGTH), AfterValidator(_plain_https)
]

Signal = Literal["rate", "errors", "latency"]
# The services list's two orderings (`services/router.py`), the same ranking a top-N
# chart uses to choose its lines.
Order = Literal["worst", "slowest"]
# A top-N chart's lines: more than five cannot be told apart by colour and dash (FR6).
TopCount = Annotated[int, Field(ge=1, le=5)]
Width = Literal[3, 4, 6, 8, 12]
Height = Literal["small", "medium", "large"]
RefreshSeconds = Literal[30, 60, 300]

SMALL: Final = "small"


class _Strict(BaseModel):
    model_config = ConfigDict(extra="forbid", frozen=True)


class Picker(_Strict):
    """The dashboard-wide service picker, in place of a named service (D7)."""

    picker: Literal[True]


ServiceRef = ServiceName | Picker


class ProjectTrendSettings(_Strict):
    signal: Signal


class ServiceTrendSettings(_Strict):
    service: ServiceRef
    signal: Signal


class TopServicesTrendSettings(_Strict):
    signal: Signal
    order: Order
    count: TopCount


def _known_metric(value: str) -> str:
    if value not in INFRASTRUCTURE_METRIC_NAMES:
        raise ValueError("must be one of the infrastructure screen's metric names")
    return value


InfrastructureMetric = Annotated[str, AfterValidator(_known_metric)]
# One part of a node's identity: empty when the node did not name it.
NodePart = Annotated[
    str, StringConstraints(max_length=NAME_MAX_LENGTH), AfterValidator(_refuse_nul)
]


class NodeRef(_Strict):
    """One node as the infrastructure screen identifies it: a host, a container, or the
    process that reported readings naming neither (`infrastructure/service.NodeKey`).
    All four parts, because a host name alone cannot pick a container on it."""

    host: NodePart
    container: NodePart
    reporter: NodePart
    reporter_instance: NodePart

    @model_validator(mode="after")
    def _names_a_node(self) -> NodeRef:
        if not (self.host or self.container or self.reporter):
            raise ValueError("a node names a host, a container or the service that reported it")
        return self


class NodeTrendSettings(_Strict):
    node: NodeRef
    metric: InfrastructureMetric


class NoteSettings(_Strict):
    text: NoteText


class _Panel(_Strict):
    id: PanelId
    title: Label | None
    width: Width
    height: Height


class _TimePanel(_Panel):
    """A chart: `small` leaves it about 48 px of plot, so it is refused (FR5, AC67)."""

    @model_validator(mode="after")
    def _not_small(self) -> _TimePanel:
        if self.height == SMALL:
            raise ValueError("a chart cannot be small; choose medium or large")
        return self


class ProjectTrendPanel(_TimePanel):
    kind: Literal["project_trend"]
    settings: ProjectTrendSettings


class ServiceTrendPanel(_TimePanel):
    kind: Literal["service_trend"]
    settings: ServiceTrendSettings


class TopServicesTrendPanel(_TimePanel):
    kind: Literal["top_services_trend"]
    settings: TopServicesTrendSettings


class NodeTrendPanel(_TimePanel):
    kind: Literal["node_trend"]
    settings: NodeTrendSettings


class NotePanel(_Panel):
    kind: Literal["note"]
    settings: NoteSettings


KnownPanel = (
    ProjectTrendPanel | ServiceTrendPanel | TopServicesTrendPanel | NodeTrendPanel | NotePanel
)
Panel = Annotated[KnownPanel, Field(discriminator="kind")]
TIME_KINDS: Final = frozenset(
    {"project_trend", "service_trend", "top_services_trend", "node_trend"}
)


class Link(_Strict):
    label: Label
    url: LinkAddress


class Definition(_Strict):
    schema_version: Literal[1]
    refresh_seconds: RefreshSeconds | None
    default_range: RangeId | None
    service_picker: bool
    links: Annotated[list[Link], Field(max_length=MAX_LINKS)]
    panels: list[Panel]

    @model_validator(mode="after")
    def _panels_fit(self) -> Definition:
        if len(self.panels) > MAX_PANELS:
            raise ValueError(
                f"a dashboard holds {MAX_PANELS} panels, because each one reads the database; "
                f"this one has {len(self.panels)}. Split it into two"
            )
        ids = [panel.id for panel in self.panels]
        repeated = sorted({panel_id for panel_id in ids if ids.count(panel_id) > 1})
        if repeated:
            raise ValueError(f"panel ids must be unique; repeated: {repeated}")
        if not self.service_picker and any(uses_picker(panel) for panel in self.panels):
            raise ValueError("a panel names the service picker, and the picker is off")
        return self


class DashboardDocument(_Strict):
    title: Title
    description: Description
    definition: Definition


def uses_picker(panel: Panel | UnknownPanel) -> bool:
    """Whether a panel reads the service the dashboard's picker holds."""
    return isinstance(panel, ServiceTrendPanel) and isinstance(panel.settings.service, Picker)


def document_bytes(document: dict[str, Any]) -> int:
    """A document's size as stored: compact JSON, UTF-8."""
    return len(json.dumps(document, separators=(",", ":"), ensure_ascii=False).encode())


def _refuse_oversized(document: dict[str, Any]) -> None:
    size = document_bytes(document)
    if size > MAX_DOCUMENT_BYTES:
        raise InvalidRequestError(
            f"A dashboard is at most 64 KiB; this one is {size // 1024} KiB. "
            "Shorten its notes or remove panels.",
            size_bytes=size,
        )


def parse_document(document: dict[str, Any]) -> DashboardDocument:
    """A document from a file or a test, or a refusal naming what is wrong (FR7)."""
    _refuse_oversized(document)
    return DashboardDocument.model_validate(document)


def check_size(document: DashboardDocument) -> None:
    """The 64 KiB cap, for a document a route has already validated field by field."""
    _refuse_oversized(
        document.model_dump(mode="json", include={"title", "description", "definition"})
    )


def canonical_json(value: Any) -> str:
    """One spelling of a definition, so its hash changes only when its content does."""
    return json.dumps(value, sort_keys=True, separators=(",", ":"), ensure_ascii=False)


def link_hosts(definition: Definition | StoredDefinition) -> list[str]:
    """The hosts a definition's links point at: what an audit entry may keep (FR27)."""
    return sorted({urlsplit(link.url).hostname or "" for link in definition.links} - {""})


# ----------------------------------------------------------------- reading


class UnknownPanel(BaseModel):
    """A stored panel this code cannot read: its kind is gone, or it no longer validates.
    It keeps a place on the page and says so (FR8)."""

    model_config = ConfigDict(frozen=True)

    id: str
    kind: Literal["unknown_kind"] = UNKNOWN_KIND
    title: str | None = None
    width: Width = 12
    height: Height = "medium"


class StoredDefinition(BaseModel):
    """A definition as read back: its settings, and each panel known or unknown."""

    model_config = ConfigDict(frozen=True)

    refresh_seconds: RefreshSeconds | None = None
    default_range: RangeId | None = None
    service_picker: bool = False
    links: list[Link] = []
    panels: list[KnownPanel | UnknownPanel]


_PANEL: Final = TypeAdapter[Panel](Panel)
# Each dashboard-wide setting read alone, so one that no longer validates falls back to
# its default rather than taking the page with it.
_SETTINGS: Final[dict[str, TypeAdapter[Any]]] = {
    "refresh_seconds": TypeAdapter(RefreshSeconds | None),
    "default_range": TypeAdapter(RangeId | None),
    "service_picker": TypeAdapter(bool),
    "links": TypeAdapter(Annotated[list[Link], Field(max_length=MAX_LINKS)]),
}


def parse_stored(stored: dict[str, Any]) -> StoredDefinition:
    """A stored definition, panel by panel: one bad panel never takes the page (FR8)."""
    panels: list[KnownPanel | UnknownPanel] = []
    for position, raw in enumerate(stored.get("panels") or [], start=1):
        try:
            panels.append(_PANEL.validate_python(raw))
        except ValidationError:
            panels.append(_unknown(raw, position))
    settings: dict[str, Any] = {}
    for name, adapter in _SETTINGS.items():
        if name in stored:
            try:
                settings[name] = adapter.validate_python(stored[name])
            except ValidationError:
                continue
    return StoredDefinition(**settings, panels=panels)


def _unknown(raw: Any, position: int) -> UnknownPanel:
    fields = raw if isinstance(raw, dict) else {}
    panel_id = fields.get("id")
    width, height = fields.get("width"), fields.get("height")
    return UnknownPanel(
        id=panel_id if isinstance(panel_id, str) and panel_id else f"panel_{position}",
        width=width if width in (3, 4, 6, 8, 12) else 12,
        height=height if height in ("small", "medium", "large") else "medium",
    )
