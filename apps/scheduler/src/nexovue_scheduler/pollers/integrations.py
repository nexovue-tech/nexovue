"""Reading door 4b connectors out of Postgres, and parsing what they configure.

Same arrangement as `checks.py`: the `integrations` table is owned by the API,
this service only reads it, and it reads by column name rather than by importing
the API's models — the two deploy separately, and a scheduler that cannot start
because a control-plane package moved is a scheduler running nobody's polls.

Nothing here is a secret. Under ADR 0076 an integration stores a role ARN and an
ExternalId, both public values, and the credential that actually opens the door
is minted per poll and thrown away. The column is still called
`config_encrypted` because it was named before that decision; it holds plain
UTF-8 JSON, and the name is now misleading rather than wrong-in-effect.
"""

from __future__ import annotations

import uuid
from dataclasses import dataclass
from typing import Any, Final

from sqlalchemy import text
from sqlalchemy.ext.asyncio import AsyncEngine

from nexovue_scheduler.pollers.aws import RoleGrant
from nexovue_scheduler.pollers.postgres_connect import AUTH_RDS_IAM, DEFAULT_PORT, DatabaseTarget

KIND_CLOUDWATCH: Final = "cloudwatch"
KIND_POSTGRES: Final = "postgres"

STATUS_ACTIVE: Final = "active"
# Set when a poll fails. The row stays scheduled — a trust policy is fixed in
# the customer's account, and we cannot know when — but the status is what lets
# them see it is broken instead of wondering why a graph is empty.
STATUS_FAILING: Final = "failing"

_RECORD_SUCCESS: Final = text(
    """
    UPDATE integrations
    SET last_sync_at = now(), status = :status, last_error = NULL
    WHERE id = :id
    """
)

_RECORD_FAILURE: Final = text(
    """
    UPDATE integrations
    SET status = :status, last_error = :reason
    WHERE id = :id
    """
)

_ACTIVE_INTEGRATIONS: Final = text(
    """
    SELECT id, org_id, project_id, kind, config, external_id, interval_seconds
    FROM integrations
    WHERE status = :status
    ORDER BY id
    """
)


# Long enough for AWS's own message, short enough that a hostile one cannot fill
# the column.
MAX_ERROR_LENGTH: Final = 500


class IntegrationConfigError(ValueError):
    """A stored connector that cannot be turned into a poll."""


@dataclass(frozen=True, slots=True)
class IntegrationDefinition:
    """One row of `integrations`, as the scheduler sees it.

    Carries `org_id` and `project_id` because the poll that runs from it has to
    stamp them on the envelope — a reading that reaches the broker without a
    tenant is a reading nothing can attribute or isolate.
    """

    id: uuid.UUID
    org_id: uuid.UUID
    project_id: uuid.UUID
    kind: str
    config: dict[str, Any]
    # Generated by the control plane and never by the customer, which is the
    # whole of its value (ADR 0076). A connector without one cannot be polled.
    external_id: uuid.UUID | None
    interval_seconds: int

    @property
    def schedule_name(self) -> str:
        """The name this connector goes by in the beat schedule.

        The row id, not the kind: one project may connect two AWS accounts, and
        a name collision would silently drop one of them.
        """
        return f"integration:{self.id}"


async def load_active_integrations(engine: AsyncEngine) -> list[IntegrationDefinition]:
    """Every active connector, for one refresh of the beat schedule.

    A row whose config will not parse is skipped rather than raising. One
    customer's broken connector must not stop every other customer's polls from
    being scheduled.
    """
    async with engine.connect() as connection:
        rows = (
            (await connection.execute(_ACTIVE_INTEGRATIONS, {"status": STATUS_ACTIVE}))
            .mappings()
            .all()
        )

    definitions = []
    for row in rows:
        # A connector with no ExternalId cannot assume anything, so scheduling
        # it would only produce a failing poll every interval forever.
        if row["external_id"] is None:
            continue
        definitions.append(
            IntegrationDefinition(
                id=row["id"],
                org_id=row["org_id"],
                project_id=row["project_id"],
                kind=row["kind"],
                config=row["config"] or {},
                external_id=row["external_id"],
                interval_seconds=row["interval_seconds"],
            )
        )
    return definitions


async def record_poll_succeeded(engine: AsyncEngine, integration_id: uuid.UUID) -> None:
    """Say when this connector last worked.

    Without this the column is always NULL and a customer cannot tell a healthy
    integration from one that has never once succeeded.
    """
    async with engine.begin() as connection:
        await connection.execute(_RECORD_SUCCESS, {"id": integration_id, "status": STATUS_ACTIVE})


async def record_poll_failed(engine: AsyncEngine, integration_id: uuid.UUID, reason: str) -> None:
    """Say that this connector is broken, and why.

    The reason is the exception's text, truncated. It comes from AWS and names
    what went wrong — a trust policy that does not allow us, an ExternalId that
    does not match — which is exactly what the customer needs to fix it. It
    carries no credential: the whole point of ADR 0076 is that we hold none.
    """
    async with engine.begin() as connection:
        await connection.execute(
            _RECORD_FAILURE,
            {"id": integration_id, "status": STATUS_FAILING, "reason": reason[:MAX_ERROR_LENGTH]},
        )


def role_grant_from(config: dict[str, Any], external_id: str | None) -> RoleGrant:
    """The two public values that let us into a customer's AWS account.

    The role ARN is the customer's to give; the ExternalId is ours to generate
    and is read from its own column rather than from `config`. AWS requires it
    to be unguessable and not chosen by the customer, and a key inside a JSON
    blob the customer submits is precisely a value the customer chose.
    """
    role_arn = config.get("role_arn")
    if not isinstance(role_arn, str) or not role_arn:
        raise IntegrationConfigError("an AWS integration needs a string `role_arn`")
    if external_id is None:
        raise IntegrationConfigError("this integration has no external id, so no role to assume")
    return RoleGrant(role_arn=role_arn, external_id=external_id)


def rds_instances_from(config: dict[str, Any]) -> list[str]:
    """Which RDS instances to read. Named explicitly rather than discovered:
    a poller that expands to every instance in an account bills the customer for
    metrics they never asked us to watch."""
    identifiers = config.get("db_instance_identifiers")
    if not isinstance(identifiers, list) or not all(isinstance(one, str) for one in identifiers):
        raise IntegrationConfigError(
            "a CloudWatch integration needs `db_instance_identifiers` as a list of strings"
        )
    return [str(one) for one in identifiers]


def database_target_from(config: dict[str, Any], external_id: str | None = None) -> DatabaseTarget:
    """Which database to read and how we may authenticate to it."""
    host = config.get("host")
    database = config.get("database")
    user = config.get("user")
    if not isinstance(host, str) or not isinstance(database, str) or not isinstance(user, str):
        raise IntegrationConfigError(
            "a Postgres integration needs string `host`, `database` and `user`"
        )

    auth = str(config.get("auth", AUTH_RDS_IAM))
    grant = role_grant_from(config, external_id) if auth == AUTH_RDS_IAM else None
    return DatabaseTarget(
        host=host,
        port=int(config.get("port", DEFAULT_PORT)),
        database=database,
        user=user,
        auth=auth,
        grant=grant,
    )
