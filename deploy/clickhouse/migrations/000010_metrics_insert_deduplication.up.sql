-- Invariant 3 says counts derived pre-sampling stay exact. A worker crash
-- between writing a minute's counters and committing the offsets breaks that:
-- on restart it resumes from the last commit, re-counts the same spans, and
-- writes the minute a second time. Live evidence during M2 showed 15–88
-- duplicated rows per minute across restarts.
--
-- ClickHouse hashes an inserted block and drops one it has seen before — but
-- `non_replicated_deduplication_window` defaults to **0**, so a plain MergeTree
-- deduplicates nothing until the window is opened. 1000 blocks is far more than
-- a restart's replay can consume.
--
-- This works only because the re-derived block is byte-identical: `derive.Drain`
-- sorts its points, since Go randomises map iteration and an unsorted drain
-- produces a different block every call for the same counts.
ALTER TABLE metrics MODIFY SETTING non_replicated_deduplication_window = 1000
